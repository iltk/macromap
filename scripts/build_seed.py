"""Generate Flyway repeatable seed migrations from scripts/data/.

Inputs:
  api/aw_nutrition.xlsx           -> regenerates data/menus/aw.csv
  data/menus/<slug>.csv           -> menu items per chain
  data/toronto_locations.json     -> from fetch_osm_locations.py

Outputs (repeatable: Flyway re-runs them whenever their content changes):
  api/src/main/resources/db/migration/R__1_restaurants_and_menus.sql
  api/src/main/resources/db/migration/R__2_toronto_locations.sql
"""
import csv
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from xlsx_reader import read_rows  # noqa: E402

REPO = ROOT.parent
MENUS = ROOT / "data" / "menus"
MIGRATIONS = REPO / "api" / "src" / "main" / "resources" / "db" / "migration"
AW_XLSX = REPO / "api" / "aw_nutrition.xlsx"
CSV_FIELDS = ["menu_category", "name", "serving_g", "calories", "fat_g", "protein_g", "carbs_g", "source", "last_verified", "allergens"]

RESTAURANTS = [
    # slug, name, category, website, description, brand colour
    ("aw", "A&W", "restaurant", "https://web.aw.ca/",
     "Burgers, breakfast sandwiches, poutine and root beer", "#e36b0a"),
    ("mcdonalds", "McDonald's", "restaurant", "https://www.mcdonalds.com/ca/en-ca.html",
     "Burgers, chicken, fries and all-day breakfast", "#ffbc0d"),
    ("tim-hortons", "Tim Hortons", "cafe", "https://www.timhortons.ca/",
     "Coffee, breakfast sandwiches, wraps, soups and Timbits", "#c8102e"),
]


def q(v) -> str:
    if v is None or v == "":
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def num(v):
    if v is None or str(v).strip() == "":
        return None
    f = float(v)
    return int(f) if f.is_integer() else round(f, 2)


def aw_xlsx_to_csv() -> None:
    # allergens aren't in the spreadsheet; keep whatever was entered by hand in aw.csv
    existing_allergens = {}
    if (MENUS / "aw.csv").exists():
        with open(MENUS / "aw.csv", newline="") as f:
            existing_allergens = {r["name"]: r.get("allergens") or "" for r in csv.DictReader(f)}
    rows = read_rows(str(AW_XLSX))
    header = rows[0]
    flag_col = header.index("Flag") if "Flag" in header else None
    out = []
    for r in rows[1:]:
        r = r + [None] * (len(header) - len(r))
        category, item, prep, serving, cal, fat, protein, carbs = r[:8]
        if not item or not cal:  # skip empty rows / zero-calorie placeholders
            continue
        name = item if prep in (None, "", "Regular") else f"{item} ({prep})"
        source = "A&W Canada nutrition guide (aw_nutrition.xlsx)"
        if flag_col is not None and r[flag_col]:
            source += "; needs check: macros don't add up to stated calories"
        out.append({
            "menu_category": category, "name": name, "serving_g": serving, "calories": cal,
            "fat_g": fat, "protein_g": protein, "carbs_g": carbs, "source": source, "last_verified": "",
            "allergens": existing_allergens.get(name, ""),
        })
    with open(MENUS / "aw.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(out)
    print(f"aw.csv: {len(out)} items from {AW_XLSX.name}")


def build_menus_sql() -> str:
    lines = [
        "-- GENERATED by scripts/build_seed.py. Do not edit by hand.",
        "",
    ]
    for slug, name, category, website, description, color in RESTAURANTS:
        lines.append(
            "INSERT INTO restaurants (slug, name, category, website, description, brand_color) VALUES "
            f"({q(slug)}, {q(name)}, {q(category)}, {q(website)}, {q(description)}, {q(color)}) "
            "ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, category = EXCLUDED.category, "
            "website = EXCLUDED.website, description = EXCLUDED.description, brand_color = EXCLUDED.brand_color;"
        )
    lines.append("")
    for slug, *_ in RESTAURANTS:
        path = MENUS / f"{slug}.csv"
        rid = f"(SELECT id FROM restaurants WHERE slug = {q(slug)})"
        lines.append(f"DELETE FROM menu_items WHERE restaurant_id = {rid};")
        if not path.exists():
            continue
        with open(path, newline="") as f:
            items = [r for r in csv.DictReader(f) if (r.get("name") or "").strip()]
        print(f"{slug}: {len(items)} menu items")
        for r in items:
            serving = num(r.get("serving_g"))
            lines.append(
                "INSERT INTO menu_items (id, restaurant_id, name, menu_category, serving_size, calories, protein, carbs, fat, source, last_verified, allergens) VALUES "
                f"(gen_random_uuid(), {rid}, {q(r['name'].strip())}, {q(r.get('menu_category'))}, "
                f"{q(f'{serving} g' if serving else None)}, {q(num(r.get('calories')))}, {q(num(r.get('protein_g')))}, "
                f"{q(num(r.get('carbs_g')))}, {q(num(r.get('fat_g')))}, {q(r.get('source'))}, {q(r.get('last_verified'))}, "
                f"{q((r.get('allergens') or '').strip())});"
            )
        lines.append("")
    return "\n".join(lines)


def build_locations_sql() -> str:
    locs = json.loads((ROOT / "data" / "toronto_locations.json").read_text())
    lines = [
        "-- GENERATED by scripts/build_seed.py from OpenStreetMap data.",
        "-- Location data (c) OpenStreetMap contributors, available under the ODbL.",
        "",
    ]
    for r in locs:
        address = r["address"] or ""
        if r.get("postcode"):
            address = f"{address}, {r['postcode']}" if address else r["postcode"]
        address = f"{address}, {r['city']}, ON" if address else f"{r['city']}, ON"
        lines.append(
            "INSERT INTO restaurant_locations (id, restaurant_id, osm_id, latitude, longitude, address, city, phone, opening_hours) VALUES "
            f"(gen_random_uuid(), (SELECT id FROM restaurants WHERE slug = {q(r['slug'])}), {r['osm_id']}, {r['lat']}, {r['lon']}, "
            f"{q(address)}, {q(r['city'])}, {q(r['phone'])}, {q(r['opening_hours'])}) "
            "ON CONFLICT (osm_id) DO UPDATE SET restaurant_id = EXCLUDED.restaurant_id, latitude = EXCLUDED.latitude, "
            "longitude = EXCLUDED.longitude, address = EXCLUDED.address, city = EXCLUDED.city, phone = EXCLUDED.phone, "
            "opening_hours = EXCLUDED.opening_hours;"
        )
    ids = ", ".join(str(r["osm_id"]) for r in locs)
    lines += ["", f"DELETE FROM restaurant_locations WHERE osm_id IS NOT NULL AND osm_id NOT IN ({ids});", ""]
    print(f"locations: {len(locs)}")
    return "\n".join(lines)


def main() -> None:
    if AW_XLSX.exists():
        aw_xlsx_to_csv()
    (MIGRATIONS / "R__1_restaurants_and_menus.sql").write_text(build_menus_sql())
    (MIGRATIONS / "R__2_toronto_locations.sql").write_text(build_locations_sql())
    print(f"wrote seed migrations to {MIGRATIONS.relative_to(REPO)}")


if __name__ == "__main__":
    main()
